/* engine-draw GDI draw-site signatures (DrawSitesSig.h) on bytes around every known site of the owner's exes
   (selftest/drawsites-snippets.h, generated by tools/engine-sigs/draw-sites-fixture.cjs): each snippet's signature matches
   once, at the call; the same bytes with another IAT slot, or with the pattern's first byte changed, match nothing; no other
   signature of the table matches the snippet. Exit code = failures. */
#include "../DrawSitesSig.h"
#include "drawsites-snippets.h"
#include <cstdio>
#include <cstring>
#include <string>
#include <vector>
static int Failures = 0;
static void Check(bool ok, const std::string &what) { printf("%s %s\n", ok ? "PASS" : "FAIL", what.c_str()); if (!ok) Failures++; }
static std::vector<unsigned char> Bytes(const char *hex) {
  std::vector<unsigned char> v; for (size_t i = 0; hex[i] && hex[i + 1]; i += 2) { unsigned b; sscanf(hex + i, "%2x", &b); v.push_back((unsigned char)b); }
  return v;
}
static const DrawSitesSig::Sig *SigOf(const char *id) { for (const auto &g : DrawSitesSig::Sigs) if (!strcmp(g.id, id)) return &g; return nullptr; }
int main() {
  for (const auto &s : DrawSiteSnippets) {
    auto b = Bytes(s.hex); const auto *g = SigOf(s.id); std::string n = std::string(s.name) + " (" + s.id + ")";
    Check(g != nullptr, n + ": signature in the table"); if (!g) continue;
    std::uint32_t slot = s.slot, other = s.slot + 4; size_t at[4];
    int k = DrawSitesSig::Find(b.data(), b.size(), &slot, 1, g->pre, at, 4);
    Check(k == 1 && at[0] == (size_t)s.callOffset, n + ": one site, at the call");
    Check(DrawSitesSig::Find(b.data(), b.size(), &other, 1, g->pre, at, 4) == 0, n + ": another API slot, no match");
    unsigned char pb[64], pm[64]; int len = DrawSitesSig::Pattern(g->pre, pb, pm, 64);
    auto c = b; for (int i = 0; i < len; i++) if (pm[i] == 0xff) { c[s.callOffset - len + i] ^= 0x5a; break; }
    Check(DrawSitesSig::Find(c.data(), c.size(), &slot, 1, g->pre, at, 4) == 0, n + ": pattern byte changed, no match");
    for (const auto &o : DrawSitesSig::Sigs) if (strcmp(o.id, s.id) && !strcmp(o.api, g->api))
      Check(DrawSitesSig::Find(b.data(), b.size(), &slot, 1, o.pre, at, 4) == 0, n + ": not " + o.id);
  }
  unsigned char pb[8], pm[8];
  Check(DrawSitesSig::Pattern("52 ?? ff", pb, pm, 8) == 3 && pb[0] == 0x52 && pm[1] == 0 && pb[2] == 0xff, "pattern parse");
  Check(DrawSitesSig::Pattern("8b 3d SLOT 50", pb, pm, 8) == 7 && pm[1] == 0xff && pm[2] == 2 && pm[5] == 2 && pb[6] == 0x50, "pattern parse: SLOT");
  Check(DrawSitesSig::SjisLead(0x82) && DrawSitesSig::SjisLead(0xe0) && !DrawSitesSig::SjisLead('a') && !DrawSitesSig::SjisLead(0xa0), "SJIS lead bytes");
  printf("draw sites signature: %d failure(s)\n", Failures);
  return Failures;
}
