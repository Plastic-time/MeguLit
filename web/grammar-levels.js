/* The first hit of a point in a line, as code-point offsets: {start,end,text} or null. Longest form first. */
export function findHit(point,text){
 const s=[...String(text||'')].join(''),word=/[\p{L}]/u;let best=null;
 for(const h of [...point.hits].sort((a,b)=>[...b].length-[...a].length))for(let at=s.indexOf(h);at>=0;at=s.indexOf(h,at+1)){
  const prev=s[at-1]||'';if(point.after&&(point.after==='word'?!word.test(prev):!(prev&&point.after.includes(prev))))continue;
  if(point.not&&point.not.some(n=>s.startsWith(n,at)))continue;
  const start=[...s.slice(0,at)].length;if(!best||start<best.start)best={start,end:start+[...h].length,text:h};break;}
 return best;
}
