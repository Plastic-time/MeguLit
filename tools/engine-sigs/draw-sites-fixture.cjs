'use strict';
/* Writes the GDI draw-site fixtures from the owner's exes (read only): for every file in validation/fixtures/engine-sigs/
   draw-sites-files.json, each site the table matches gives a snippet (0x40 bytes before the call to 0x10 after), the
   module's IAT slot of the API, the call's VA and the file's SHA-256. Output: validation/fixtures/engine-sigs/draw-sites.json
   (the JS test) and native/megulithook/selftest/drawsites-snippets.h (the native self-test). Run after adding a signature:
     node tools/engine-sigs/draw-sites-fixture.cjs */
const fs=require('node:fs'),path=require('node:path'),crypto=require('node:crypto'),S=require('./draw-sites.cjs');
const root=path.join(__dirname,'..','..'),dir=path.join(root,'validation','fixtures','engine-sigs');
const files=JSON.parse(fs.readFileSync(path.join(dir,'draw-sites-files.json'),'utf8'));
const out={note:'generated by tools/engine-sigs/draw-sites-fixture.cjs from the owner\'s files (read only)',snippets:{}};
for(const f of files){
 if(!fs.existsSync(f.path)){console.error('missing '+f.path);continue;}
 const buf=fs.readFileSync(f.path),p=S.pe(buf),sha=crypto.createHash('sha256').update(buf).digest('hex');
 for(const g of S.sigs()){if(g.id!==f.id)continue;const sl=p.slots(g.api);
  let k=0;for(const c of p.code)for(const o of S.find(c.bytes,sl,g.pre)){const from=Math.max(0,o-0x40),to=Math.min(c.bytes.length,o+0x10);
   out.snippets[f.name+(k?'#'+k:'')]={id:g.id,file:path.basename(f.path),sha256:sha,api:g.api,va:'0x'+(c.va+from).toString(16),callOffset:o-from,slot:'0x'+c.bytes.readUInt32LE(o+2).toString(16),call:'0x'+(c.va+o).toString(16),hex:c.bytes.subarray(from,to).toString('hex')};k++;}}
}
fs.writeFileSync(path.join(dir,'draw-sites.json'),JSON.stringify(out,null,1)+'\n');
const rows=Object.entries(out.snippets).map(([n,s])=>`  { "${n}", "${s.id}", ${s.slot}u, ${s.callOffset}, "${s.hex}" },`);
fs.writeFileSync(path.join(root,'native','megulithook','selftest','drawsites-snippets.h'),
 '// SPDX-License-Identifier: GPL-3.0-or-later\n// generated by tools/engine-sigs/draw-sites-fixture.cjs: bytes around each GDI draw site of the owner\'s exes (read only)\n#pragma once\n'+
 'struct DrawSiteSnippet { const char *name, *id; unsigned slot; int callOffset; const char *hex; };\nstatic const DrawSiteSnippet DrawSiteSnippets[] = {\n'+rows.join('\n')+'\n};\n');
console.log(Object.keys(out.snippets).length+' snippet(s)');
